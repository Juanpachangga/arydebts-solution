import assert from 'node:assert/strict';
import {createAssistantHandler} from './assistant-handler.mjs';
import {createRegistrationHandler72} from './registration-handler-v72.mjs';
const origin='https://juanpachangga.github.io';
const request=(body,type='application/json')=>new Request('https://api.example.test',{method:'POST',headers:{Origin:origin,'Content-Type':type},body});
const data=JSON.stringify({messages:[{role:'user',content:'Ayuda'}]});
const opts={apiKey:'synthetic',model:'synthetic',verifySession:async()=>({id:'test'}),consumeQuota:async()=>true,fetchImpl:async()=>Response.json({output:[]})};
const assistant=createAssistantHandler(opts);
for(const raw of ['{','null','[]','42',JSON.stringify({messages:[null]})])assert.equal((await assistant(request(raw))).status,400);
assert.equal((await assistant(request(data,'text/plain'))).status,415);
assert.equal((await assistant(request('x'.repeat(32769)))).status,413);
assert.equal((await assistant(request('🤖'.repeat(9000)))).status,413,'Limits count bytes, not characters');
assert.equal((await createAssistantHandler({...opts,fetchImpl:async()=>{throw new Error('network')}})(request(data))).status,502);
assert.equal((await createAssistantHandler({...opts,fetchImpl:async()=>{throw new DOMException('timeout','TimeoutError')}})(request(data))).status,504);
assert.equal((await createAssistantHandler({...opts,verifySession:async()=>{throw new Error('session outage')}})(request(data))).status,503);
let created=0;const registration=createRegistrationHandler72({secret:'synthetic',allowedOrigin:origin,hostname:'test',consumeQuota:async()=>true,createAccount:async()=>{created++;return {success:true}}});
for(const raw of ['{','null','[]','42'])assert.equal((await registration(request(raw))).status,400);
assert.equal((await registration(request('x'.repeat(8193)))).status,413);
assert.equal((await registration(request('🤖'.repeat(2100)))).status,413);
assert.equal(created,0);
console.log('PASS API malformed JSON, null records, byte-limited streaming bodies, media types, transport timeout/outage status and no account creation on invalid input');
